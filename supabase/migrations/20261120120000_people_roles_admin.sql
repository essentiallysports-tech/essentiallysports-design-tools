-- The identities whose role is fixed in code (matches dashboard-data.js).
create or replace function public.es_designer_fixed_role(candidate_email text)
returns text
language sql
immutable
set search_path = public
as $$
  select case lower(trim(coalesce(candidate_email, '')))
    when 'suhail.quraishi@essentiallysports.com' then 'Server Owner'
    when 'designteam@essentiallysports.com' then 'Server Owner'
    when 'manish.kalsi@essentiallysports.com' then 'Super Admin'
    else null
  end;
$$;

revoke all on function public.es_designer_fixed_role(text) from public, anon;
grant execute on function public.es_designer_fixed_role(text) to authenticated;

-- ---------------------------------------------------------------------------
-- 4. Audit table (created first: the functions below write to it)
-- ---------------------------------------------------------------------------

create table if not exists public.es_designer_role_audit (
  id bigint generated by default as identity primary key,
  action text not null,
  actor_email text not null default '',
  target_email text not null default '',
  from_value text not null default '',
  to_value text not null default '',
  created_at timestamptz not null default now(),
  constraint es_designer_role_audit_action_check
    check (action in ('role_change', 'email_confirmed', 'access_request'))
);

create index if not exists es_designer_role_audit_created_at_idx
  on public.es_designer_role_audit (created_at desc);

alter table public.es_designer_role_audit enable row level security;

revoke all on public.es_designer_role_audit from public, anon, authenticated;
grant select on public.es_designer_role_audit to authenticated;

drop policy if exists "Dashboard admins can read role audit" on public.es_designer_role_audit;
create policy "Dashboard admins can read role audit"
  on public.es_designer_role_audit
  for select
  to authenticated
  using ((select public.is_es_designer_admin()));

-- ---------------------------------------------------------------------------
-- 1. Admin check: fixed emails, or an ES account with an admin role.
-- ---------------------------------------------------------------------------

create or replace function public.is_es_designer_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select lower(coalesce((select auth.jwt()) ->> 'email', '')) as email
  )
  select
    public.es_designer_fixed_role(me.email) is not null
    or (
      split_part(me.email, '@', 2) = 'essentiallysports.com'
      and exists (
        select 1
        from public.es_designer_profiles as profile
        where profile.email = me.email
          and profile.access_role in ('Admin', 'Super Admin', 'Server Owner')
      )
    )
  from me;
$$;

-- Who may assign roles: the fixed owners, or an ES account whose role is
-- 'Server Owner' (which only a fixed owner can grant).
create or replace function public.can_manage_es_designer_roles()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select lower(coalesce((select auth.jwt()) ->> 'email', '')) as email
  )
  select
    public.es_designer_fixed_role(me.email) = 'Server Owner'
    or (
      split_part(me.email, '@', 2) = 'essentiallysports.com'
      and exists (
        select 1
        from public.es_designer_profiles as profile
        where profile.email = me.email
          and profile.access_role = 'Server Owner'
      )
    )
  from me;
$$;

revoke all on function public.can_manage_es_designer_roles() from public, anon;
grant execute on function public.can_manage_es_designer_roles() to authenticated;

-- ---------------------------------------------------------------------------
-- 2. Role columns change only through the RPC.
-- ---------------------------------------------------------------------------

create or replace function public.prevent_dashboard_role_self_edit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  fixed_role text := public.es_designer_fixed_role(new.email);
begin
  if fixed_role is not null then
    new.access_role := fixed_role;
    new.role := fixed_role;
  elsif coalesce(current_setting('frameup.role_change', true), '') <> 'allowed' then
    new.access_role := old.access_role;
    new.role := old.role;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.protect_es_designer_role_on_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  fixed_role text := public.es_designer_fixed_role(new.email);
  profile_role text;
begin
  new.email := lower(trim(coalesce(new.email, '')));
  if fixed_role is not null then
    new.access_role := fixed_role;
    new.role := fixed_role;
  elsif coalesce(current_setting('frameup.role_change', true), '') = 'allowed' then
    null; -- written by admin_set_es_designer_role()
  elsif tg_table_name = 'es_designer_presence' then
    -- Presence mirrors the profile's role; it never grants one.
    select access_role into profile_role
    from public.es_designer_profiles
    where email = new.email;
    new.access_role := coalesce(profile_role, 'Associate');
    new.role := coalesce(profile_role, 'Associate');
  else
    new.access_role := 'Associate';
    new.role := 'Associate';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_es_designer_profile_roles on public.es_designer_profiles;
create trigger protect_es_designer_profile_roles
  before update on public.es_designer_profiles
  for each row execute function public.prevent_dashboard_role_self_edit();

drop trigger if exists protect_es_designer_presence_roles on public.es_designer_presence;
create trigger protect_es_designer_presence_roles
  before update on public.es_designer_presence
  for each row execute function public.prevent_dashboard_role_self_edit();

drop trigger if exists protect_es_designer_profile_roles_insert on public.es_designer_profiles;
create trigger protect_es_designer_profile_roles_insert
  before insert on public.es_designer_profiles
  for each row execute function public.protect_es_designer_role_on_insert();

drop trigger if exists protect_es_designer_presence_roles_insert on public.es_designer_presence;
create trigger protect_es_designer_presence_roles_insert
  before insert on public.es_designer_presence
  for each row execute function public.protect_es_designer_role_on_insert();

-- ---------------------------------------------------------------------------
-- 3. Change a role (Server Owners only, guarded, audited).
--    Errors carry a machine code in HINT: not_allowed, invalid_role,
--    invalid_email, self_change, protected, owner_only, last_admin.
-- ---------------------------------------------------------------------------

create or replace function public.admin_set_es_designer_role(target_email text, target_role text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor text := lower(coalesce((select auth.jwt()) ->> 'email', ''));
  normalized_email text := lower(trim(coalesce(target_email, '')));
  normalized_role text := trim(coalesce(target_role, ''));
  admin_roles text[] := array['Admin', 'Super Admin', 'Server Owner'];
  previous_role text;
  remaining_admins integer;
begin
  if not public.can_manage_es_designer_roles() then
    raise exception 'Only a Server Owner can change roles.' using hint = 'not_allowed', errcode = '42501';
  end if;
  if normalized_role not in ('Associate', 'Admin', 'Super Admin', 'Server Owner') then
    raise exception 'Choose Associate, Admin, Super Admin or Server Owner.' using hint = 'invalid_role';
  end if;
  if normalized_email = '' or split_part(normalized_email, '@', 2) <> 'essentiallysports.com' then
    raise exception 'Only EssentiallySports emails can hold a dashboard role.' using hint = 'invalid_email';
  end if;
  if normalized_email = actor then
    raise exception 'You can''t change your own role. Ask another Server Owner.' using hint = 'self_change';
  end if;
  if public.es_designer_fixed_role(normalized_email) is not null then
    raise exception 'This person''s role is fixed and can''t be changed here.' using hint = 'protected';
  end if;

  -- Lock the row so two admins can't race past the last-admin check.
  select access_role into previous_role
  from public.es_designer_profiles
  where email = normalized_email
  for update;
  previous_role := coalesce(previous_role, 'Associate');

  if (previous_role = 'Server Owner' or normalized_role = 'Server Owner')
     and previous_role <> normalized_role
     and public.es_designer_fixed_role(actor) is distinct from 'Server Owner' then
    raise exception 'Only a founding Server Owner can grant or remove Server Owner.' using hint = 'owner_only';
  end if;

  if previous_role = any(admin_roles) and not (normalized_role = any(admin_roles)) then
    select count(*) into remaining_admins
    from (
      select email from public.es_designer_profiles
      where access_role = any(admin_roles) and email <> normalized_email
      union
      select fixed.email from (values
        ('suhail.quraishi@essentiallysports.com'),
        ('designteam@essentiallysports.com'),
        ('manish.kalsi@essentiallysports.com')
      ) as fixed(email)
      where fixed.email <> normalized_email
    ) as admins;
    if remaining_admins < 1 then
      raise exception 'FrameUp needs at least one admin. Promote someone else first.' using hint = 'last_admin';
    end if;
  end if;

  if previous_role = normalized_role then
    return jsonb_build_object('email', normalized_email, 'role', normalized_role, 'previous_role', previous_role, 'changed', false);
  end if;

  perform set_config('frameup.role_change', 'allowed', true);

  update public.es_designer_profiles
  set access_role = normalized_role, role = normalized_role, updated_at = now()
  where email = normalized_email;

  if not found then
    insert into public.es_designer_profiles (email, name, role, access_role, designation, last_seen_at, created_at, updated_at)
    values (normalized_email, split_part(normalized_email, '@', 1), normalized_role, normalized_role, 'Designer', null, now(), now());
  end if;

  update public.es_designer_presence
  set access_role = normalized_role, role = normalized_role, updated_at = now()
  where email = normalized_email;

  perform set_config('frameup.role_change', '', true);

  insert into public.es_designer_role_audit (action, actor_email, target_email, from_value, to_value)
  values ('role_change', actor, normalized_email, previous_role, normalized_role);

  return jsonb_build_object(
    'email', normalized_email,
    'role', normalized_role,
    'previous_role', previous_role,
    'changed', true,
    'changed_at', now()
  );
end;
$$;

revoke all on function public.admin_set_es_designer_role(text, text) from public, anon;
grant execute on function public.admin_set_es_designer_role(text, text) to authenticated;

-- The older entry point keeps working, with the same guards and audit.
create or replace function public.set_es_designer_access_role(target_email text, target_role text)
returns public.es_designer_profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_profile public.es_designer_profiles;
begin
  perform public.admin_set_es_designer_role(target_email, target_role);
  select * into updated_profile
  from public.es_designer_profiles
  where email = lower(trim(coalesce(target_email, '')));
  return updated_profile;
end;
$$;

revoke all on function public.set_es_designer_access_role(text, text) from public, anon;
grant execute on function public.set_es_designer_access_role(text, text) to authenticated;

