-- 5. People list with sign-up status (admins only).
-- ---------------------------------------------------------------------------

create or replace function public.admin_list_es_designer_people()
returns table (
  email text,
  name text,
  designation text,
  access_role text,
  avatar_url text,
  workspace text,
  last_seen_at timestamptz,
  account_created_at timestamptz,
  email_confirmed_at timestamptz,
  invited_at timestamptz,
  last_sign_in_at timestamptz,
  has_account boolean,
  is_fixed_role boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_es_designer_admin() then
    raise exception 'Only dashboard admins can list people.' using hint = 'not_allowed', errcode = '42501';
  end if;

  return query
  with accounts as (
    select
      lower(trim(u.email)) as email,
      u.created_at,
      u.email_confirmed_at,
      u.invited_at,
      u.last_sign_in_at,
      nullif(trim(coalesce(u.raw_user_meta_data ->> 'name', '')), '') as meta_name
    from auth.users as u
    where u.email is not null
      and u.deleted_at is null
  ),
  everyone as (
    select a.email from accounts a
    union
    select p.email from public.es_designer_profiles p
  )
  select
    e.email,
    coalesce(nullif(p.name, ''), a.meta_name, split_part(e.email, '@', 1))::text,
    coalesce(nullif(p.designation, ''), '')::text,
    coalesce(public.es_designer_fixed_role(e.email), p.access_role, 'Associate')::text,
    coalesce(nullif(pr.avatar_url, ''), nullif(p.avatar_url, ''), '')::text,
    coalesce(pr.workspace, '')::text,
    greatest(p.last_seen_at, pr.last_seen_at),
    a.created_at,
    a.email_confirmed_at,
    a.invited_at,
    a.last_sign_in_at,
    (a.email is not null),
    (public.es_designer_fixed_role(e.email) is not null)
  from everyone e
  left join accounts a on a.email = e.email
  left join public.es_designer_profiles p on p.email = e.email
  left join public.es_designer_presence pr on pr.email = e.email
  order by greatest(p.last_seen_at, pr.last_seen_at) desc nulls last, e.email;
end;
$$;

revoke all on function public.admin_list_es_designer_people() from public, anon;
grant execute on function public.admin_list_es_designer_people() to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Confirm a stuck account's email by hand (admins only).
--    Hints: not_allowed, not_found, already_confirmed, not_approved.
-- ---------------------------------------------------------------------------

create or replace function public.admin_confirm_es_designer_email(target_email text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor text := lower(coalesce((select auth.jwt()) ->> 'email', ''));
  normalized_email text := lower(trim(coalesce(target_email, '')));
  target_id uuid;
  confirmed timestamptz;
begin
  if not public.is_es_designer_admin() then
    raise exception 'Only dashboard admins can confirm accounts.' using hint = 'not_allowed', errcode = '42501';
  end if;
  if not public.is_es_designer_email_approved(normalized_email) then
    raise exception 'This email isn''t approved for FrameUp.' using hint = 'not_approved';
  end if;

  select u.id, u.email_confirmed_at into target_id, confirmed
  from auth.users as u
  where lower(trim(u.email)) = normalized_email
    and u.deleted_at is null
  limit 1
  for update;

  if target_id is null then
    raise exception 'There''s no FrameUp account for this email yet.' using hint = 'not_found';
  end if;
  if confirmed is not null then
    return jsonb_build_object('email', normalized_email, 'confirmed', true, 'changed', false, 'confirmed_at', confirmed);
  end if;

  update auth.users
  set email_confirmed_at = now(), updated_at = now()
  where id = target_id;

  insert into public.es_designer_role_audit (action, actor_email, target_email, from_value, to_value)
  values ('email_confirmed', actor, normalized_email, 'unconfirmed', 'confirmed');

  return jsonb_build_object('email', normalized_email, 'confirmed', true, 'changed', true, 'confirmed_at', now());
end;
$$;

revoke all on function public.admin_confirm_es_designer_email(text) from public, anon;
grant execute on function public.admin_confirm_es_designer_email(text) to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Audit access-request decisions.
-- ---------------------------------------------------------------------------

create or replace function public.audit_es_designer_access_request()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status then
    insert into public.es_designer_role_audit (action, actor_email, target_email, from_value, to_value)
    values (
      'access_request',
      lower(coalesce((select auth.jwt()) ->> 'email', '')),
      new.email,
      coalesce(old.status, ''),
      coalesce(new.status, '')
    );
  end if;
  return new;
end;
$$;

drop trigger if exists es_designer_access_request_audit on public.es_designer_access_requests;
create trigger es_designer_access_request_audit
  after update on public.es_designer_access_requests
  for each row execute function public.audit_es_designer_access_request();

